def get_total_users() -> int:
    supabase = get_supabase()
    resp = supabase.table("users").select("phone_number", count="exact").execute()
    return resp.count if resp.count is not None else 0

def get_total_checks() -> int:
    supabase = get_supabase()
    resp = supabase.table("usage").select("id", count="exact").execute()
    return resp.count if resp.count is not None else 0

def get_paid_users() -> int:
    supabase = get_supabase()
    resp = supabase.table("users").select("phone_number", count="exact").eq("is_paid", True).execute()
    return resp.count if resp.count is not None else 0
